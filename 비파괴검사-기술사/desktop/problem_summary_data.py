def summary_for_problem(problem: dict) -> tuple[str, str]:
    """제목 관련성이 보장된 요약과 선정 근거를 반환한다."""
    number = problem.get("number")
    if number in EXACT_SUMMARIES:
        return EXACT_SUMMARIES[number], "문제별 검토"
    title = problem.get("title", "").lower()
    for keywords, summary in KEYWORD_SUMMARIES:
        if any(keyword in title for keyword in keywords):
            return summary, "제목 핵심어"
    group = problem.get("study_group", "종합·기타")
    return GROUP_SUMMARIES.get(group, GROUP_SUMMARIES["종합·기타"]), "원리그룹"
